const assert=require('node:assert/strict');
require('../engine.js');require('../planner.js');
const S=Scheduler,P=Planner,week='2026-11-02';
const shifts=[{id:'n',name:'Amanecida',starts_at:'00:00',ends_at:'08:00'},{id:'o',name:'Apertura',starts_at:'08:00',ends_at:'16:00'},{id:'c',name:'Cierre',starts_at:'16:00',ends_at:'00:00'}];
const employees=Array.from({length:6},(_,i)=>({id:'e'+i,full_name:'Persona '+i,role:i===5?'entrenador':'full_time',area:'produccion',weekly_hours:48,work_days:6}));
const ctx={employees,shifts,studies:[],restrictions:[],meetings:[],requirements:Array.from({length:7},(_,i)=>shifts.map(s=>({weekday:i+1,shift_id:s.id,area:'produccion',minimum_staff:1}))).flat(),rules:{}};
const row=(id,d,sh)=>P.assignment(employees.find(e=>e.id===id),d,sh.starts_at,8,'produccion',shifts);
const result=S.generate(ctx,week)[0],stats=S.balance(result.assignments,ctx,week);
assert.equal(result.diagnostics.hardIssues.length,0);
assert.equal(result.diagnostics.missingContractHours,0);
assert.equal(result.diagnostics.gaps.filter(g=>g.area==='produccion').length,0);
assert(stats.every(r=>r.consecutive===0),'El caso factible debe evitar amanecidas seguidas');
assert(stats.every(r=>r.counts.every(n=>n>=1&&n<=3)),'Todos los FT y entrenadores deben rotar');
assert.equal(stats.length,6,'Incluye al entrenador en el mismo reparto');
const pt={...employees[0],id:'pt',role:'part_time',weekly_hours:19.5};
assert.equal(S.score(result.assignments,ctx,week),S.score(result.assignments,{...ctx,employees:[...employees,pt]},week),'PT no cambia el puntaje de FT');
const lock={employee_id:'e0',shift_date:week,assignment:result.assignments.find(a=>a.employee_id==='e0'&&a.shift_date===week)||null};
const restDay=Array.from({length:7},(_,i)=>S.add(week,i)).find(d=>!result.assignments.some(a=>a.employee_id==='e1'&&a.shift_date===d));
const lockedCtx={...ctx,lockedCells:[lock,{employee_id:'e1',shift_date:restDay,assignment:null}]};
const lockedResult=S.generate(lockedCtx,week)[0];
assert.equal(lockedResult.diagnostics.hardIssues.length,0);
assert(!lockedResult.assignments.some(a=>a.employee_id==='e1'&&a.shift_date===restDay));
const actual=lockedResult.assignments.find(a=>a.employee_id==='e0'&&a.shift_date===week)||null;
assert.deepEqual(actual,lock.assignment);
const prev=row('e0',S.add(week,-1),shifts[2]);
assert.match(S.hard(row('e0',week,shifts[0]),[],{...ctx,boundaryAssignments:[prev]}),/Descanso/);
const sunNight=row('e0',S.add(week,-1),shifts[0]);
assert.equal(S.balance([row('e0',week,shifts[0])],{...ctx,historyAssignments:[sunNight]},week)[0].consecutive,1);
const copy=P.copyWeek(result.assignments,week,S.add(week,7));
assert.equal(copy.length,result.assignments.length);
assert.equal(copy[0].shift_date,S.add(result.assignments[0].shift_date,7));
assert.equal(S.h(copy[0]),S.h(result.assignments[0]));
assert.equal(S.changes(copy,copy,S.add(week,7)).length,0);
const equivalent=copy.map(a=>({...a,starts_at:new Date(a.starts_at).toISOString(),ends_at:new Date(a.ends_at).toISOString(),segments:[]}));
assert.equal(S.changes(equivalent,copy,S.add(week,7)).length,0,'Equivalencia de zonas horarias y segmentos implícitos');
assert.throws(()=>S.generate({...ctx,lockedCells:[{employee_id:'e0',shift_date:week,assignment:row('e1',week,shifts[0])}]},week),/fijaciones/);
const unavailable={...ctx,restrictions:[{employee_id:'e0',kind:'personal',date_from:week,date_to:week}]};
assert(S.preflight({...unavailable,employees:[employees[0]]},week).some(x=>x.includes('produccion')));
assert.throws(()=>P.swap([row('e0',week,shifts[0]),row('e1',week,shifts[1])],'e0','e1',week,{...ctx,studies:[{employee_id:'e1',weekday:1,starts_at:'00:00',ends_at:'08:00'}]}),/Estudios/);
console.log('OK: rotación FT/entrenador, cobertura, fijaciones, historial, copia y restricciones');

// Un gerente confirmado se conserva completo al recalcular producción y servicio.
const manager={id:'manager',full_name:'Gerente',role:'gerente',area:'gerencial',weekly_hours:48,work_days:6};
const managerCtx={...ctx,employees:[...employees,manager]};
const managerialResult=S.generate(managerCtx,week)[0];
const confirmed=Array.from({length:7},(_,i)=>{const d=S.add(week,i);return {employee_id:manager.id,shift_date:d,assignment:managerialResult.assignments.find(a=>a.employee_id===manager.id&&a.shift_date===d)||null}});
const regenerated=S.generate({...managerCtx,lockedCells:confirmed},week)[0];
assert.equal(regenerated.diagnostics.hardIssues.length,0);
assert.deepEqual(regenerated.assignments.filter(a=>a.employee_id===manager.id),managerialResult.assignments.filter(a=>a.employee_id===manager.id));
console.log('OK: gerenciales confirmados se conservan en la regeneración');
